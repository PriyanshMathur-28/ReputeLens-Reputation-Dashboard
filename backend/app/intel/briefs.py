from typing import Dict, Any


def generate_executive_brief(
    brand_name: str,
    period_days: int,
    health_score: float,
    health_delta: float,
    kpis: Dict[str, Any],
    top_positive: list,
    top_negative: list,
    response_verdict: str = "Effective"
) -> str:
    """Generates a structured 10-section Executive PR Brief in Markdown (Section 14.6, F22)."""
    vol = kpis.get("mentions", {}).get("value", 2250)
    net_s = kpis.get("net_sentiment", {}).get("value", 24.5)
    sov = kpis.get("share_of_voice", {}).get("value", 0.58) * 100
    crisis_r = kpis.get("crisis_risk", {}).get("value", 20.0)

    md = f"""# ReputeLens Executive Brief: {brand_name}
**Reporting Window:** Last {period_days} Days | **Generated By:** ReputeLens Intelligence Engine

---

### 1. Executive Headline
{brand_name} maintained an overall health score of **{health_score}/100** during this period, demonstrating solid baseline customer engagement alongside an acute, well-mitigated mid-cycle crisis event.

### 2. Reputation Health Score Breakdown
- **Current Score:** {health_score} / 100 ({'+' if health_delta >= 0 else ''}{health_delta:.1f} pts change)
- **Primary Health Driver:** Net sentiment momentum and customer satisfaction in Zentro Gold subscription tiers.

### 3. Key Performance Indicators
| Metric | Current Value | Period-over-Period Delta |
| :--- | :--- | :--- |
| **Total Volume** | {vol:,} mentions | +28.4% |
| **Net Sentiment** | {net_s:.1f}% | -12.6% |
| **Share of Voice** | {sov:.1f}% | +8.2% |
| **Crisis Risk** | {crisis_r:.1f} / 100 | Stable (Low band) |

### 4. Top Positive Conversation Drivers
1. **Zentro Gold Subscription Value**: High satisfaction around zero delivery charges and priority restaurant access.
2. **Food Quality & Taste**: Praise for signature biryani bowls and paneer preparations across tier-1 cities.
3. **App Experience**: Smooth checkout updates and real-time delivery map tracking.

### 5. Top Negative Conversation Drivers
1. **Packaging & Hygiene Concerns**: Viral Day 45 incident regarding plastic contamination reports.
2. **Customer Care Wait Times**: Ticket resolution delays during peak volume hours.
3. **Delivery Delay Cues**: Peak-hour delays during weekend monsoon spells.

### 6. Emerging Narratives
- **Food Quality Verification**: Rapidly emerging community focus on restaurant hygiene standards and kitchen audits following the day 45 incident.

### 7. Social Network Insights
- **Influencer Ecosystem**: Key opinion leaders (@foodie_truths_in) commanded disproportionate initial reach during the quality debate.
- **Inauthentic Activity**: A 25-account synthetic cluster was detected and isolated, attempting to artificially inflate #BoycottZentro hashtags.

### 8. Competitor Benchmarking
- **vs QuickBite**: QuickBite suffered an app outage on day 32, driving users toward Zentro with a net sentiment advantage of +14 points.
- **vs Tiffino**: Tiffino experienced suspicious 5-star review bursts, maintaining lower overall organic volume.

### 9. Response Effectiveness
- **Public Intervention (Day 47)**: The official acknowledgment, audit confirmation, and proactive refund outreach yielded an **{response_verdict}** verdict, reducing daily negative volume by over 48% within 72 hours.

### 10. Prioritized Strategic Recommendations
1. **Publish Kitchen Audit Results**: Release visual proof of packaging inspections to permanently neutralize residual hygiene doubts.
2. **Dedicated VIP Support Routing**: Implement automated routing for complaints from authors with >10k followers.
3. **Expand Hinglish Support Templates**: Train support personnel on colloquial Hinglish phrasing to improve first-response sentiment.
"""
    return md
